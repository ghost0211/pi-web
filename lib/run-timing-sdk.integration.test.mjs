import assert from "node:assert/strict";
import test from "node:test";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { ModelRuntime, DefaultResourceLoader, SettingsManager, SessionManager, createAgentSession } from "@earendil-works/pi-coding-agent";
import { AssistantMessageEventStream } from "@earendil-works/pi-ai";
import { createJiti } from "jiti";
const jiti = createJiti(import.meta.url, { tsconfigPaths: true });
const { AgentSessionWrapper } = await jiti.import("./rpc-manager.ts");
const { buildSessionHistory } = await jiti.import("./session-reader.ts");

test("real SDK tool loop records once at settled, survives reopen, and never exposes timing to the model", async t => {
  const root = await mkdtemp(join(tmpdir(), "pi-run-timing-sdk-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  const runtime = await ModelRuntime.create({ authPath: join(root, "auth.json"), modelsPath: null, modelsStorePath: join(root, "models-store.json"), refreshOnCreate: false });
  runtime.registerProvider("timing-fixture", { api: "openai-completions", baseUrl: "https://fixture.invalid", apiKey: "fixture-not-real", models: [{ id: "model", name: "Fixture", reasoning: false, input: ["text"], contextWindow: 100000, maxTokens: 1000, cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0 } }] });
  const settings = SettingsManager.inMemory({ retry: { enabled: false }, compaction: { enabled: false } });
  const manager = SessionManager.create(root, root);
  const loader = new DefaultResourceLoader({ cwd: root, agentDir: root, settingsManager: settings, noExtensions: true, noSkills: true, noPromptTemplates: true, noThemes: true, noContextFiles: true });
  await loader.reload();
  let executions = 0;
  const { session } = await createAgentSession({ cwd: root, agentDir: root, sessionManager: manager, settingsManager: settings, modelRuntime: runtime, model: runtime.getModel("timing-fixture", "model"), resourceLoader: loader, tools: ["fixture_tool"], customTools: [{ name: "fixture_tool", label: "Fixture", description: "No side effects", parameters: { type: "object", properties: {} }, execute: async () => { executions++; await new Promise(resolve => setTimeout(resolve, 25)); return { content: [{ type: "text", text: "tool result" }], details: {} }; } }] });
  const oldTimeout = process.env.PI_WEB_SESSION_IDLE_TIMEOUT_MS;
  process.env.PI_WEB_SESSION_IDLE_TIMEOUT_MS = "0";
  const wrapper = new AgentSessionWrapper(session);
  t.after(() => { wrapper.destroy(); if (oldTimeout === undefined) delete process.env.PI_WEB_SESSION_IDLE_TIMEOUT_MS; else process.env.PI_WEB_SESSION_IDLE_TIMEOUT_MS = oldTimeout; });
  wrapper.start();
  let requests = 0;
  const modelContexts = [];
  session.agent.streamFunction = (model, context) => {
    modelContexts.push(context.messages);
    requests++;
    const tool = requests === 1;
    const message = { role: "assistant", api: model.api, provider: model.provider, model: model.id, timestamp: Date.now(), content: tool ? [{ type: "toolCall", id: "fixture-call", name: "fixture_tool", arguments: {} }] : [{ type: "text", text: "final answer" }], stopReason: tool ? "toolUse" : "stop", usage: { input: 1, output: 1, cacheRead: 0, cacheWrite: 0, totalTokens: 2, cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0, total: 0 } } };
    const stream = new AssistantMessageEventStream();
    queueMicrotask(() => { stream.push({ type: "start", partial: message }); stream.push({ type: "done", reason: message.stopReason, message }); stream.end(); });
    return stream;
  };
  const records = () => manager.getEntries().filter(e => e.type === "custom" && e.customType === "pi-web:run-timing");
  session.subscribe(event => {
    if (event.type === "tool_execution_start") assert.ok(wrapper.getRunningStartedAt());
    if (event.type === "agent_end") assert.equal(records().length, requests === 2 ? 0 : 1, "agent_end is not a logical-run settlement");
  });
  await session.prompt("Use the fixture tool once");
  assert.equal(executions, 1);
  assert.equal(records().length, 1);
  assert.ok(records()[0].data.durationMs >= 20, "tool execution is included in wall elapsed duration");
  const assistantEntries = manager.getEntries().filter(e => e.type === "message" && e.message.role === "assistant");
  assert.equal(records()[0].data.finalAssistantEntryId, assistantEntries.at(-1).id);
  const firstDuration = records()[0].data.durationMs;
  const firstId = records()[0].data.finalAssistantEntryId;
  await session.prompt("Next round");
  assert.equal(records().length, 2);
  assert.notEqual(records()[0].data.runId, records()[1].data.runId);
  assert.equal(wrapper.getRunningStartedAt(), null);
  const reopened = SessionManager.open(manager.getSessionFile());
  const history = buildSessionHistory(reopened.getEntries());
  const firstAnswer = history.messages[history.entryIds.indexOf(firstId)];
  assert.equal(firstAnswer.runDurationMs, firstDuration);
  assert.equal(firstAnswer.runDurationEstimated, false);
  for (const context of modelContexts) assert.doesNotMatch(JSON.stringify(context), /pi-web:run-timing|runDurationMs|finalAssistantEntryId/);
});
